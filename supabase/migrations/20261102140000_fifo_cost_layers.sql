-- FIFO cost layers for general (non-Kuasi) SIPB inventory.
-- Receipts retain their own purchase price. Outgoing details consume the oldest
-- available layer by receipt date and ID; cancellations return that exact layer.

CREATE TABLE IF NOT EXISTS public.sipb_fifo_layers (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  barang_id integer NOT NULL REFERENCES public.barang(id) ON DELETE RESTRICT,
  barang_masuk_id integer REFERENCES public.barang_masuk(id) ON DELETE RESTRICT,
  source_type text NOT NULL CHECK (source_type IN ('BARANG_MASUK','OPNAME','MIGRASI_LEGACY','MIGRASI_PENYESUAIAN')),
  source_ref_id integer,
  tanggal_masuk date NOT NULL,
  jumlah_masuk integer NOT NULL CHECK (jumlah_masuk > 0),
  sisa integer NOT NULL CHECK (sisa >= 0 AND sisa <= jumlah_masuk),
  harga_satuan numeric(20,4) NOT NULL DEFAULT 0 CHECK (harga_satuan >= 0),
  harga_estimasi boolean NOT NULL DEFAULT false,
  catatan text,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_sipb_fifo_layer_receipt
  ON public.sipb_fifo_layers(barang_masuk_id) WHERE barang_masuk_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uq_sipb_fifo_layer_source
  ON public.sipb_fifo_layers(source_type,source_ref_id) WHERE source_ref_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_sipb_fifo_available
  ON public.sipb_fifo_layers(barang_id,tanggal_masuk,id) WHERE sisa > 0;

CREATE TABLE IF NOT EXISTS public.sipb_fifo_allocations (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  layer_id bigint NOT NULL REFERENCES public.sipb_fifo_layers(id) ON DELETE RESTRICT,
  source_type text NOT NULL CHECK (source_type IN ('BARANG_KELUAR','OPNAME','MIGRASI')),
  detail_barang_keluar_id integer REFERENCES public.detail_barang_keluar(id) ON DELETE CASCADE,
  riwayat_opname_id integer REFERENCES public.riwayat_opname(id) ON DELETE CASCADE,
  jumlah integer NOT NULL CHECK (jumlah > 0),
  harga_satuan numeric(20,4) NOT NULL DEFAULT 0 CHECK (harga_satuan >= 0),
  catatan text,
  reversed_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  CHECK (
    (source_type='BARANG_KELUAR' AND detail_barang_keluar_id IS NOT NULL AND riwayat_opname_id IS NULL AND catatan IS NULL)
    OR (source_type='OPNAME' AND detail_barang_keluar_id IS NULL AND riwayat_opname_id IS NOT NULL AND catatan IS NULL)
    OR (source_type='MIGRASI' AND detail_barang_keluar_id IS NULL AND riwayat_opname_id IS NULL AND catatan IS NOT NULL)
  )
);
CREATE INDEX IF NOT EXISTS idx_sipb_fifo_alloc_detail
  ON public.sipb_fifo_allocations(detail_barang_keluar_id) WHERE detail_barang_keluar_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_sipb_fifo_alloc_layer_active
  ON public.sipb_fifo_allocations(layer_id) WHERE reversed_at IS NULL;

ALTER TABLE public.sipb_fifo_layers ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.sipb_fifo_allocations ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS sipb_fifo_layers_active_read ON public.sipb_fifo_layers;
CREATE POLICY sipb_fifo_layers_active_read ON public.sipb_fifo_layers
  FOR SELECT TO authenticated USING (public.sipb_is_active_user());
DROP POLICY IF EXISTS sipb_fifo_allocations_active_read ON public.sipb_fifo_allocations;
CREATE POLICY sipb_fifo_allocations_active_read ON public.sipb_fifo_allocations
  FOR SELECT TO authenticated USING (public.sipb_is_active_user());
GRANT SELECT ON public.sipb_fifo_layers, public.sipb_fifo_allocations TO authenticated;
REVOKE INSERT,UPDATE,DELETE,TRUNCATE ON public.sipb_fifo_layers,public.sipb_fifo_allocations FROM PUBLIC,anon,authenticated;

CREATE OR REPLACE FUNCTION public.sipb_fifo_is_kuasi(p_barang_id integer)
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path=public AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.barang b
    LEFT JOIN public.kategori k ON k.id=b.kategori_id
    WHERE b.id=p_barang_id
      AND lower(COALESCE(k.nama_kategori,b.kategori,'')) LIKE '%kuasi%'
  );
$$;
REVOKE ALL ON FUNCTION public.sipb_fifo_is_kuasi(integer) FROM PUBLIC,anon,authenticated;

-- Internal backfill/rebuild. Unknown legacy balances are represented as
-- explicitly estimated layers and reconciled to barang.sisa without changing it.
CREATE OR REPLACE FUNCTION public.sipb_fifo_rebuild_internal()
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE
  e record;
  l record;
  b record;
  need_qty integer;
  available_qty integer;
  take_qty integer;
  remaining_qty integer;
  estimate_price numeric(20,4);
  layer_count integer := 0;
  allocation_count integer := 0;
  estimate_count integer := 0;
BEGIN
  PERFORM set_config('sipb.fifo_rebuilding','on',true);
  DELETE FROM public.sipb_fifo_allocations;
  DELETE FROM public.sipb_fifo_layers;

  INSERT INTO public.sipb_fifo_layers(
    barang_id,barang_masuk_id,source_type,tanggal_masuk,jumlah_masuk,sisa,harga_satuan,harga_estimasi
  )
  SELECT bm.barang_id,bm.id,'BARANG_MASUK',bm.tanggal_masuk,bm.jumlah,bm.jumlah,bm.harga_satuan,false
  FROM public.barang_masuk bm
  JOIN public.barang b ON b.id=bm.barang_id
  LEFT JOIN public.kategori k ON k.id=b.kategori_id
  WHERE bm.jumlah>0
    AND NOT (lower(COALESCE(k.nama_kategori,b.kategori,'')) LIKE '%kuasi%');

  INSERT INTO public.sipb_fifo_layers(
    barang_id,source_type,source_ref_id,tanggal_masuk,jumlah_masuk,sisa,
    harga_satuan,harga_estimasi,catatan
  )
  SELECT o.barang_id,'OPNAME',o.id,o.tanggal_opname,o.selisih,o.selisih,
         COALESCE((
           SELECT bm.harga_satuan FROM public.barang_masuk bm
           WHERE bm.barang_id=o.barang_id AND bm.tanggal_masuk<=o.tanggal_opname
           ORDER BY bm.tanggal_masuk DESC,bm.id DESC LIMIT 1
         ),b.harga_terakhir,0),
         true,'Penambahan hasil Stock Opname; harga referensi bersifat estimasi'
  FROM public.riwayat_opname o
  JOIN public.barang b ON b.id=o.barang_id
  LEFT JOIN public.kategori k ON k.id=b.kategori_id
  WHERE o.selisih>0
    AND NOT (lower(COALESCE(k.nama_kategori,b.kategori,'')) LIKE '%kuasi%');

  FOR e IN
    SELECT event_type,source_id,barang_id,event_date,qty,detail_id
    FROM (
      SELECT 'BARANG_KELUAR'::text event_type,t.id source_id,d.barang_id,
             t.tanggal_keluar event_date,d.jumlah qty,d.id detail_id
      FROM public.detail_barang_keluar d
      JOIN public.transaksi_keluar t ON t.id=d.transaksi_keluar_id
      JOIN public.barang b ON b.id=d.barang_id
      LEFT JOIN public.kategori k ON k.id=b.kategori_id
      WHERE COALESCE(t.status,'AKTIF')='AKTIF'
        AND NOT (lower(COALESCE(k.nama_kategori,b.kategori,'')) LIKE '%kuasi%')
      UNION ALL
      SELECT 'OPNAME'::text,o.id,o.barang_id,o.tanggal_opname,abs(o.selisih)::integer,NULL::integer
      FROM public.riwayat_opname o
      JOIN public.barang b ON b.id=o.barang_id
      LEFT JOIN public.kategori k ON k.id=b.kategori_id
      WHERE o.selisih<0
        AND NOT (lower(COALESCE(k.nama_kategori,b.kategori,'')) LIKE '%kuasi%')
    ) movements
    ORDER BY event_date,CASE WHEN event_type='BARANG_KELUAR' THEN 1 ELSE 2 END,source_id,detail_id NULLS FIRST
  LOOP
    need_qty := e.qty;
    SELECT COALESCE(SUM(sisa),0)::integer INTO available_qty
    FROM public.sipb_fifo_layers
    WHERE barang_id=e.barang_id AND tanggal_masuk<=e.event_date AND sisa>0;

    IF available_qty<need_qty THEN
      SELECT COALESCE(harga_terakhir,0)::numeric(20,4) INTO estimate_price
      FROM public.barang WHERE id=e.barang_id;
      INSERT INTO public.sipb_fifo_layers(
        barang_id,source_type,tanggal_masuk,jumlah_masuk,sisa,harga_satuan,harga_estimasi,catatan
      ) VALUES (
        e.barang_id,'MIGRASI_LEGACY',DATE '1900-01-01',
        need_qty-available_qty,need_qty-available_qty,COALESCE(estimate_price,0),true,
        'Saldo historis sintetis karena riwayat penerimaan lama tidak lengkap'
      );
      estimate_count := estimate_count+1;
    END IF;

    FOR l IN
      SELECT id,sisa,harga_satuan FROM public.sipb_fifo_layers
      WHERE barang_id=e.barang_id AND tanggal_masuk<=e.event_date AND sisa>0
      ORDER BY tanggal_masuk,id FOR UPDATE
    LOOP
      EXIT WHEN need_qty<=0;
      take_qty := LEAST(need_qty,l.sisa);
      IF e.event_type='BARANG_KELUAR' THEN
        INSERT INTO public.sipb_fifo_allocations(
          layer_id,source_type,detail_barang_keluar_id,jumlah,harga_satuan
        ) VALUES(l.id,'BARANG_KELUAR',e.detail_id,take_qty,l.harga_satuan);
      ELSE
        INSERT INTO public.sipb_fifo_allocations(
          layer_id,source_type,riwayat_opname_id,jumlah,harga_satuan
        ) VALUES(l.id,'OPNAME',e.source_id,take_qty,l.harga_satuan);
      END IF;
      UPDATE public.sipb_fifo_layers SET sisa=sisa-take_qty WHERE id=l.id;
      need_qty := need_qty-take_qty;
      allocation_count := allocation_count+1;
    END LOOP;
  END LOOP;

  FOR b IN
    SELECT b.id,COALESCE(b.sisa,0)::integer sisa,
           COALESCE(b.harga_terakhir,0)::numeric(20,4) harga_terakhir
    FROM public.barang b
    LEFT JOIN public.kategori k ON k.id=b.kategori_id
    WHERE NOT (lower(COALESCE(k.nama_kategori,b.kategori,'')) LIKE '%kuasi%')
    ORDER BY b.id
  LOOP
    SELECT COALESCE(SUM(sisa),0)::integer INTO remaining_qty
    FROM public.sipb_fifo_layers WHERE barang_id=b.id;

    IF remaining_qty<b.sisa THEN
      need_qty := b.sisa-remaining_qty;
      INSERT INTO public.sipb_fifo_layers(
        barang_id,source_type,tanggal_masuk,jumlah_masuk,sisa,harga_satuan,harga_estimasi,catatan
      ) VALUES(
        b.id,'MIGRASI_PENYESUAIAN',CURRENT_DATE,need_qty,need_qty,b.harga_terakhir,true,
        'Penyesuaian saldo aktivasi FIFO; harga estimasi dari harga terakhir Master Barang'
      );
      estimate_count := estimate_count+1;
    ELSIF remaining_qty>b.sisa THEN
      need_qty := remaining_qty-b.sisa;
      FOR l IN
        SELECT id,sisa,harga_satuan FROM public.sipb_fifo_layers
        WHERE barang_id=b.id AND sisa>0 ORDER BY tanggal_masuk,id FOR UPDATE
      LOOP
        EXIT WHEN need_qty<=0;
        take_qty := LEAST(need_qty,l.sisa);
        INSERT INTO public.sipb_fifo_allocations(
          layer_id,source_type,jumlah,harga_satuan,catatan
        ) VALUES(
          l.id,'MIGRASI',take_qty,l.harga_satuan,
          'Penyesuaian migrasi agar lapisan FIFO sama dengan saldo Master Barang'
        );
        UPDATE public.sipb_fifo_layers SET sisa=sisa-take_qty WHERE id=l.id;
        need_qty := need_qty-take_qty;
        allocation_count := allocation_count+1;
      END LOOP;
    END IF;
  END LOOP;

  SELECT count(*)::integer INTO layer_count FROM public.sipb_fifo_layers;
  PERFORM set_config('sipb.fifo_rebuilding','off',true);
  RETURN jsonb_build_object('status','success','lapisan',layer_count,
    'alokasi',allocation_count,'lapisan_estimasi',estimate_count);
END;
$$;
REVOKE ALL ON FUNCTION public.sipb_fifo_rebuild_internal() FROM PUBLIC,anon,authenticated;

CREATE OR REPLACE FUNCTION public.rebuild_sipb_fifo()
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
BEGIN
  IF NOT public.sipb_is_active_user() OR NOT public.sipb_is_admin() THEN
    RAISE EXCEPTION 'Hanya admin aktif yang dapat membangun ulang lapisan FIFO';
  END IF;
  RETURN public.sipb_fifo_rebuild_internal();
END;
$$;
REVOKE ALL ON FUNCTION public.rebuild_sipb_fifo() FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.rebuild_sipb_fifo() TO authenticated;

-- Initial backfill runs as the migration owner, not as an authenticated user.
SELECT public.sipb_fifo_rebuild_internal();

CREATE OR REPLACE FUNCTION public.sipb_fifo_allocate_detail(p_detail_id integer)
RETURNS integer LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE
  d public.detail_barang_keluar%ROWTYPE;
  v_date date;
  v_status text;
  remaining integer;
  allocated integer := 0;
  l record;
  take_qty integer;
BEGIN
  SELECT * INTO d FROM public.detail_barang_keluar WHERE id=p_detail_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'Detail Barang Keluar #% tidak ditemukan',p_detail_id; END IF;
  SELECT tanggal_keluar,status INTO v_date,v_status
  FROM public.transaksi_keluar WHERE id=d.transaksi_keluar_id;
  IF NOT FOUND OR COALESCE(v_status,'AKTIF')<>'AKTIF' THEN RETURN 0; END IF;
  IF public.sipb_fifo_is_kuasi(d.barang_id) THEN RETURN 0; END IF;

  SELECT COALESCE(SUM(jumlah),0)::integer INTO allocated
  FROM public.sipb_fifo_allocations
  WHERE detail_barang_keluar_id=p_detail_id AND source_type='BARANG_KELUAR' AND reversed_at IS NULL;
  IF allocated>0 THEN
    IF allocated<>d.jumlah THEN RAISE EXCEPTION 'Alokasi FIFO detail #% tidak lengkap',p_detail_id; END IF;
    RETURN allocated;
  END IF;

  remaining := d.jumlah;
  FOR l IN
    SELECT id,sisa,harga_satuan FROM public.sipb_fifo_layers
    WHERE barang_id=d.barang_id AND tanggal_masuk<=v_date AND sisa>0
    ORDER BY tanggal_masuk,id FOR UPDATE
  LOOP
    EXIT WHEN remaining<=0;
    take_qty := LEAST(remaining,l.sisa);
    INSERT INTO public.sipb_fifo_allocations(
      layer_id,source_type,detail_barang_keluar_id,jumlah,harga_satuan
    ) VALUES(l.id,'BARANG_KELUAR',p_detail_id,take_qty,l.harga_satuan);
    UPDATE public.sipb_fifo_layers SET sisa=sisa-take_qty WHERE id=l.id;
    remaining := remaining-take_qty;
    allocated := allocated+take_qty;
  END LOOP;
  IF remaining>0 THEN
    RAISE EXCEPTION 'Lapisan FIFO barang ID % tidak cukup pada tanggal % (kurang % unit). Periksa tanggal penerimaan atau jalankan rekonsiliasi FIFO.',
      d.barang_id,v_date,remaining;
  END IF;
  RETURN allocated;
END;
$$;
REVOKE ALL ON FUNCTION public.sipb_fifo_allocate_detail(integer) FROM PUBLIC,anon,authenticated;

CREATE OR REPLACE FUNCTION public.sipb_fifo_detail_insert_trigger()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
BEGIN
  IF current_setting('sipb.fifo_rebuilding',true)='on' THEN RETURN NEW; END IF;
  PERFORM public.sipb_fifo_allocate_detail(NEW.id);
  RETURN NEW;
END;
$$;
REVOKE ALL ON FUNCTION public.sipb_fifo_detail_insert_trigger() FROM PUBLIC,anon,authenticated;
DROP TRIGGER IF EXISTS trg_sipb_fifo_detail_insert ON public.detail_barang_keluar;
CREATE TRIGGER trg_sipb_fifo_detail_insert
AFTER INSERT ON public.detail_barang_keluar
FOR EACH ROW EXECUTE FUNCTION public.sipb_fifo_detail_insert_trigger();

CREATE OR REPLACE FUNCTION public.sipb_fifo_sync_receipt_trigger()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE
  layer_id bigint;
  used_qty integer;
BEGIN
  IF current_setting('sipb.fifo_rebuilding',true)='on' THEN
    IF TG_OP='DELETE' THEN RETURN OLD; ELSE RETURN NEW; END IF;
  END IF;
  IF TG_OP='DELETE' THEN
    SELECT id INTO layer_id FROM public.sipb_fifo_layers WHERE barang_masuk_id=OLD.id FOR UPDATE;
    IF layer_id IS NOT NULL THEN
      IF EXISTS(SELECT 1 FROM public.sipb_fifo_allocations WHERE layer_id=layer_id) THEN
        RAISE EXCEPTION 'Penerimaan #% sudah memiliki riwayat alokasi FIFO dan tidak dapat dihapus',OLD.id;
      END IF;
      DELETE FROM public.sipb_fifo_layers WHERE id=layer_id;
    END IF;
    RETURN OLD;
  END IF;

  SELECT id INTO layer_id FROM public.sipb_fifo_layers WHERE barang_masuk_id=NEW.id FOR UPDATE;
  IF public.sipb_fifo_is_kuasi(NEW.barang_id) THEN
    IF layer_id IS NOT NULL THEN
      IF EXISTS(SELECT 1 FROM public.sipb_fifo_allocations WHERE layer_id=layer_id) THEN
        RAISE EXCEPTION 'Penerimaan #% memiliki riwayat FIFO dan tidak dapat diubah menjadi Kuasi',NEW.id;
      END IF;
      DELETE FROM public.sipb_fifo_layers WHERE id=layer_id;
    END IF;
    RETURN NEW;
  END IF;

  IF layer_id IS NULL THEN
    INSERT INTO public.sipb_fifo_layers(
      barang_id,barang_masuk_id,source_type,tanggal_masuk,jumlah_masuk,sisa,harga_satuan,harga_estimasi
    ) VALUES(NEW.barang_id,NEW.id,'BARANG_MASUK',NEW.tanggal_masuk,NEW.jumlah,NEW.jumlah,NEW.harga_satuan,false);
    RETURN NEW;
  END IF;

  SELECT COALESCE(SUM(jumlah),0)::integer INTO used_qty
  FROM public.sipb_fifo_allocations WHERE layer_id=layer_id AND reversed_at IS NULL;
  IF used_qty>NEW.jumlah THEN
    RAISE EXCEPTION 'Jumlah penerimaan #% tidak boleh di bawah alokasi FIFO aktif (%)',NEW.id,used_qty;
  END IF;
  IF EXISTS(
    SELECT 1 FROM public.sipb_fifo_allocations a
    LEFT JOIN public.detail_barang_keluar d ON d.id=a.detail_barang_keluar_id
    LEFT JOIN public.transaksi_keluar t ON t.id=d.transaksi_keluar_id
    LEFT JOIN public.riwayat_opname o ON o.id=a.riwayat_opname_id
    WHERE a.layer_id=layer_id AND a.reversed_at IS NULL
      AND COALESCE(t.tanggal_keluar,o.tanggal_opname)<NEW.tanggal_masuk
  ) THEN
    RAISE EXCEPTION 'Tanggal penerimaan #% tidak dapat digeser melewati transaksi yang telah memakai lapisan FIFO',NEW.id;
  END IF;
  IF TG_OP='UPDATE' AND OLD.barang_id IS DISTINCT FROM NEW.barang_id AND used_qty>0 THEN
    RAISE EXCEPTION 'Master Barang penerimaan #% tidak dapat dipindahkan karena lapisan FIFO sudah digunakan',NEW.id;
  END IF;

  UPDATE public.sipb_fifo_layers
  SET barang_id=NEW.barang_id,tanggal_masuk=NEW.tanggal_masuk,
      jumlah_masuk=NEW.jumlah,sisa=NEW.jumlah-used_qty,harga_satuan=NEW.harga_satuan,
      harga_estimasi=false,catatan=NULL
  WHERE id=layer_id;
  UPDATE public.sipb_fifo_allocations SET harga_satuan=NEW.harga_satuan WHERE layer_id=layer_id;
  RETURN NEW;
END;
$$;
REVOKE ALL ON FUNCTION public.sipb_fifo_sync_receipt_trigger() FROM PUBLIC,anon,authenticated;
DROP TRIGGER IF EXISTS trg_sipb_fifo_sync_receipt ON public.barang_masuk;
CREATE TRIGGER trg_sipb_fifo_sync_receipt
AFTER INSERT OR UPDATE OR DELETE ON public.barang_masuk
FOR EACH ROW EXECUTE FUNCTION public.sipb_fifo_sync_receipt_trigger();

CREATE OR REPLACE FUNCTION public.sipb_fifo_cancel_trigger()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE a record;
BEGIN
  IF COALESCE(OLD.status,'AKTIF')='AKTIF' AND COALESCE(NEW.status,'AKTIF')='DIBATALKAN' THEN
    FOR a IN
      SELECT x.id,x.layer_id,x.jumlah
      FROM public.sipb_fifo_allocations x
      JOIN public.detail_barang_keluar d ON d.id=x.detail_barang_keluar_id
      WHERE d.transaksi_keluar_id=NEW.id
        AND x.source_type='BARANG_KELUAR' AND x.reversed_at IS NULL
      ORDER BY x.layer_id,x.id FOR UPDATE OF x
    LOOP
      UPDATE public.sipb_fifo_layers SET sisa=sisa+a.jumlah WHERE id=a.layer_id;
      UPDATE public.sipb_fifo_allocations SET reversed_at=now() WHERE id=a.id;
    END LOOP;
  END IF;
  RETURN NEW;
END;
$$;
REVOKE ALL ON FUNCTION public.sipb_fifo_cancel_trigger() FROM PUBLIC,anon,authenticated;
DROP TRIGGER IF EXISTS trg_sipb_fifo_cancel_restore ON public.transaksi_keluar;
CREATE TRIGGER trg_sipb_fifo_cancel_restore
AFTER UPDATE OF status ON public.transaksi_keluar
FOR EACH ROW EXECUTE FUNCTION public.sipb_fifo_cancel_trigger();

CREATE OR REPLACE FUNCTION public.sipb_fifo_opname_trigger()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE
  price numeric(20,4);
  remaining integer;
  l record;
  take_qty integer;
BEGIN
  IF current_setting('sipb.fifo_rebuilding',true)='on'
     OR public.sipb_fifo_is_kuasi(NEW.barang_id) OR NEW.selisih=0 THEN RETURN NEW; END IF;
  SELECT COALESCE((
    SELECT bm.harga_satuan FROM public.barang_masuk bm
    WHERE bm.barang_id=NEW.barang_id AND bm.tanggal_masuk<=NEW.tanggal_opname
    ORDER BY bm.tanggal_masuk DESC,bm.id DESC LIMIT 1
  ),b.harga_terakhir,0)::numeric(20,4)
  INTO price FROM public.barang b WHERE b.id=NEW.barang_id;

  IF NEW.selisih>0 THEN
    INSERT INTO public.sipb_fifo_layers(
      barang_id,source_type,source_ref_id,tanggal_masuk,jumlah_masuk,sisa,
      harga_satuan,harga_estimasi,catatan
    ) VALUES(NEW.barang_id,'OPNAME',NEW.id,NEW.tanggal_opname,NEW.selisih,NEW.selisih,
      COALESCE(price,0),true,'Penambahan Stock Opname; harga referensi bersifat estimasi');
    RETURN NEW;
  END IF;

  remaining := abs(NEW.selisih);
  FOR l IN
    SELECT id,sisa,harga_satuan FROM public.sipb_fifo_layers
    WHERE barang_id=NEW.barang_id AND tanggal_masuk<=NEW.tanggal_opname AND sisa>0
    ORDER BY tanggal_masuk,id FOR UPDATE
  LOOP
    EXIT WHEN remaining<=0;
    take_qty := LEAST(remaining,l.sisa);
    INSERT INTO public.sipb_fifo_allocations(
      layer_id,source_type,riwayat_opname_id,jumlah,harga_satuan
    ) VALUES(l.id,'OPNAME',NEW.id,take_qty,l.harga_satuan);
    UPDATE public.sipb_fifo_layers SET sisa=sisa-take_qty WHERE id=l.id;
    remaining := remaining-take_qty;
  END LOOP;
  IF remaining>0 THEN
    RAISE EXCEPTION 'Stock Opname mengurangi stok melebihi lapisan FIFO barang ID % (kurang %)',NEW.barang_id,remaining;
  END IF;
  RETURN NEW;
END;
$$;
