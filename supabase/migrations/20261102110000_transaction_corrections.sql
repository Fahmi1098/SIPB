-- SIPB transaction correction and cancellation audit.
-- Apply once after 20261102090000_security_integrity_followup.sql.
-- All stock and ledger changes are performed inside SECURITY DEFINER RPCs.

CREATE TABLE IF NOT EXISTS public.sipb_transaction_audit (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entity_type text NOT NULL CHECK (entity_type IN ('BARANG_MASUK','BARANG_KELUAR','MASTER_BARANG')),
  entity_id integer NOT NULL,
  new_entity_id integer NULL,
  action text NOT NULL CHECK (action IN ('KOREKSI','PEMBATALAN','PERUBAHAN_MASTER')),
  reason text NOT NULL,
  actor_id uuid NULL,
  actor_name text NULL,
  old_data jsonb NOT NULL DEFAULT '{}'::jsonb,
  new_data jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_sipb_transaction_audit_created
  ON public.sipb_transaction_audit (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_sipb_transaction_audit_entity
  ON public.sipb_transaction_audit (entity_type, entity_id, created_at DESC);

ALTER TABLE public.sipb_transaction_audit ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.sipb_transaction_audit FROM PUBLIC, anon, authenticated;
GRANT SELECT ON TABLE public.sipb_transaction_audit TO authenticated;
DROP POLICY IF EXISTS sipb_active_transaction_audit_read
  ON public.sipb_transaction_audit;
CREATE POLICY sipb_active_transaction_audit_read
  ON public.sipb_transaction_audit
  FOR SELECT TO authenticated
  USING (public.sipb_is_active_user() AND public.sipb_is_admin());

-- Master Barang name/specification changes also leave a before/after record.
CREATE OR REPLACE FUNCTION public.audit_master_barang_identity_change()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_actor_name text;
BEGIN
  IF (OLD.kode_barang, OLD.nama_barang, OLD.keterangan, OLD.kategori_id,
      OLD.tipe, OLD.merk, OLD.satuan)
     IS DISTINCT FROM
     (NEW.kode_barang, NEW.nama_barang, NEW.keterangan, NEW.kategori_id,
      NEW.tipe, NEW.merk, NEW.satuan) THEN
    SELECT nama_lengkap INTO v_actor_name
    FROM public.user_profiles
    WHERE id = auth.uid();

    INSERT INTO public.sipb_transaction_audit (
      entity_type, entity_id, action, reason, actor_id, actor_name,
      old_data, new_data
    )
    VALUES (
      'MASTER_BARANG', OLD.id, 'PERUBAHAN_MASTER',
      'Perubahan identitas atau spesifikasi Master Barang',
      auth.uid(), v_actor_name, to_jsonb(OLD), to_jsonb(NEW)
    );
  END IF;
  RETURN NEW;
END;
$$;

REVOKE ALL ON FUNCTION public.audit_master_barang_identity_change()
  FROM PUBLIC, anon, authenticated;

DROP TRIGGER IF EXISTS trg_audit_master_barang_identity
  ON public.barang;
CREATE TRIGGER trg_audit_master_barang_identity
AFTER UPDATE OF kode_barang, nama_barang, keterangan, kategori_id, tipe, merk, satuan
ON public.barang
FOR EACH ROW
EXECUTE FUNCTION public.audit_master_barang_identity_change();

-- Correct a normal (non-Kuasi) receipt. The original receipt ID is retained.
-- Stock is adjusted by the delta; changing the selected Master Barang moves
-- the receipt quantity only when the full old quantity is still available.
CREATE OR REPLACE FUNCTION public.correct_barang_masuk(
  p_barang_masuk_id integer,
  p_barang_id integer,
  p_jumlah integer,
  p_harga_satuan numeric,
  p_sumber_dana text,
  p_tanggal date,
  p_nama_penyerah text,
  p_nama_penerima text,
  p_keterangan text,
  p_alasan text
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_receipt public.barang_masuk%ROWTYPE;
  v_source public.barang%ROWTYPE;
  v_target public.barang%ROWTYPE;
  v_source_category text;
  v_target_category text;
  v_delta integer;
  v_old_data jsonb;
  v_new_data jsonb;
  v_actor_name text;
BEGIN
  IF NOT public.sipb_is_active_user() OR NOT public.sipb_is_admin() THEN
    RAISE EXCEPTION 'Hanya admin aktif yang dapat mengoreksi Barang Masuk';
  END IF;

  IF p_barang_masuk_id IS NULL OR p_barang_id IS NULL THEN
    RAISE EXCEPTION 'Transaksi dan Master Barang wajib dipilih';
  END IF;
  IF p_jumlah IS NULL OR p_jumlah < 1 THEN
    RAISE EXCEPTION 'Jumlah Barang Masuk harus bilangan bulat positif';
  END IF;
  IF p_harga_satuan IS NULL OR p_harga_satuan < 0
     OR p_harga_satuan::text IN ('NaN','Infinity','-Infinity') THEN
    RAISE EXCEPTION 'Harga satuan harus angka nol atau lebih';
  END IF;
  IF p_tanggal IS NULL
     OR COALESCE(trim(p_nama_penyerah),'') = ''
     OR COALESCE(trim(p_nama_penerima),'') = '' THEN
    RAISE EXCEPTION 'Tanggal, penyerah, dan penerima wajib diisi';
  END IF;
  IF length(COALESCE(p_keterangan,'')) > 500
     OR length(COALESCE(trim(p_alasan),'')) < 8
     OR length(COALESCE(trim(p_alasan),'')) > 500 THEN
    RAISE EXCEPTION 'Keterangan maksimal 500 karakter dan alasan koreksi minimal 8 karakter';
  END IF;

  SELECT * INTO v_receipt
  FROM public.barang_masuk
  WHERE id = p_barang_masuk_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Transaksi Barang Masuk #% tidak ditemukan', p_barang_masuk_id;
  END IF;

  IF v_receipt.barang_id IS NULL THEN
    RAISE EXCEPTION 'Transaksi tidak memiliki referensi Master Barang';
  END IF;

  -- Lock both affected Master Barang rows in a deterministic order.
  PERFORM id
  FROM public.barang
  WHERE id IN (v_receipt.barang_id, p_barang_id)
  ORDER BY id
  FOR UPDATE;

  SELECT * INTO v_source
  FROM public.barang
  WHERE id = v_receipt.barang_id;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Master Barang asal tidak ditemukan';
  END IF;

  SELECT * INTO v_target
  FROM public.barang
  WHERE id = p_barang_id;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Master Barang tujuan tidak ditemukan';
  END IF;

  IF COALESCE(v_source.is_archived,false) OR COALESCE(v_target.is_archived,false) THEN
    RAISE EXCEPTION 'Master Barang yang diarsipkan tidak dapat digunakan untuk koreksi';
  END IF;

  SELECT nama_kategori INTO v_source_category
  FROM public.kategori WHERE id = v_source.kategori_id;
  SELECT nama_kategori INTO v_target_category
  FROM public.kategori WHERE id = v_target.kategori_id;

  -- The current Kuasi schema has batch rows without a stable receipt foreign key.
  -- Blocking these edits is safer than altering a possibly unrelated serial batch.
  IF lower(COALESCE(v_source_category,'')) LIKE '%kuasi%'
     OR lower(COALESCE(v_target_category,'')) LIKE '%kuasi%'
     OR v_receipt.nomor_dus IS NOT NULL
     OR v_receipt.nomor_awal IS NOT NULL
     OR v_receipt.nomor_akhir IS NOT NULL
     OR EXISTS (
       SELECT 1 FROM public.stok_kuasi
       WHERE barang_id IN (v_receipt.barang_id, p_barang_id)
     ) THEN
    RAISE EXCEPTION
      'Koreksi umum belum diizinkan untuk transaksi Kuasi/nomor seri. Gunakan prosedur koreksi batch Kuasi khusus agar nomor seri tidak tertukar.';
  END IF;

  v_old_data := jsonb_build_object(
    'transaksi', to_jsonb(v_receipt),
    'master_barang', to_jsonb(v_source)
  );

  IF v_receipt.barang_id = p_barang_id THEN
    v_delta := p_jumlah - v_receipt.jumlah;

    IF v_delta < 0
       AND COALESCE(v_source.sisa,0) < abs(v_delta) THEN
      RAISE EXCEPTION
        'Koreksi ditolak: stok tersedia % tidak cukup untuk mengurangi penerimaan sebesar %',
        COALESCE(v_source.sisa,0), abs(v_delta);
    END IF;

    IF COALESCE(v_source.jumlah_total,0) + v_delta < 0
       OR COALESCE(v_source.sisa,0) + v_delta < 0 THEN
      RAISE EXCEPTION 'Koreksi akan membuat saldo stok negatif';
    END IF;

    UPDATE public.barang
    SET jumlah_total = COALESCE(jumlah_total,0) + v_delta,
        sisa = COALESCE(sisa,0) + v_delta
    WHERE id = p_barang_id;
  ELSE
    IF COALESCE(v_source.sisa,0) < v_receipt.jumlah
       OR COALESCE(v_source.jumlah_total,0) < v_receipt.jumlah THEN
      RAISE EXCEPTION
        'Koreksi barang ditolak: sisa Master Barang asal (%) tidak cukup untuk memindahkan seluruh jumlah penerimaan lama (%). Selesaikan transaksi keluar terkait terlebih dahulu.',
        COALESCE(v_source.sisa,0), v_receipt.jumlah;
    END IF;

    IF COALESCE(v_target.jumlah_total,0)::bigint + p_jumlah > 2147483647
       OR COALESCE(v_target.sisa,0)::bigint + p_jumlah > 2147483647 THEN
      RAISE EXCEPTION 'Saldo Master Barang tujuan melebihi batas jumlah yang didukung';
    END IF;

    UPDATE public.barang
    SET jumlah_total = COALESCE(jumlah_total,0) - v_receipt.jumlah,
        sisa = COALESCE(sisa,0) - v_receipt.jumlah
    WHERE id = v_receipt.barang_id;

    UPDATE public.barang
    SET jumlah_total = COALESCE(jumlah_total,0) + p_jumlah,
        sisa = COALESCE(sisa,0) + p_jumlah
    WHERE id = p_barang_id;
  END IF;

  UPDATE public.barang_masuk
  SET barang_id = p_barang_id,
      jumlah = p_jumlah,
      harga_satuan = p_harga_satuan,
      sumber_dana = NULLIF(trim(p_sumber_dana),''),
      tanggal_masuk = p_tanggal,
      nama_penyerah = trim(p_nama_penyerah),
      nama_penerima = trim(p_nama_penerima),
      keterangan = NULLIF(trim(p_keterangan),'')
  WHERE id = p_barang_masuk_id
  RETURNING * INTO v_receipt;

  -- Keep the reference price aligned with the latest receipt, not the last edit.
  UPDATE public.barang b
  SET harga_terakhir = COALESCE((
    SELECT bm.harga_satuan
    FROM public.barang_masuk bm
    WHERE bm.barang_id = b.id
    ORDER BY bm.tanggal_masuk DESC, bm.id DESC
    LIMIT 1
  ), 0)
  WHERE b.id IN (v_source.id, v_target.id);

  SELECT nama_lengkap INTO v_actor_name
  FROM public.user_profiles WHERE id = auth.uid();

  SELECT jsonb_build_object(
    'transaksi', to_jsonb(bm),
    'master_barang', to_jsonb(b)
  )
  INTO v_new_data
  FROM public.barang_masuk bm
  JOIN public.barang b ON b.id = bm.barang_id
  WHERE bm.id = p_barang_masuk_id;

  INSERT INTO public.sipb_transaction_audit (
    entity_type, entity_id, action, reason, actor_id, actor_name,
    old_data, new_data
  )
  VALUES (
    'BARANG_MASUK', p_barang_masuk_id, 'KOREKSI', trim(p_alasan),
    auth.uid(), v_actor_name, v_old_data, v_new_data
  );

  RETURN jsonb_build_object(
    'status','corrected',
    'id',p_barang_masuk_id,
    'barang_id',p_barang_id,
    'jumlah_lama',v_old_data->'transaksi'->>'jumlah',
    'jumlah_baru',p_jumlah
  );
END;
$$;

REVOKE ALL ON FUNCTION public.correct_barang_masuk(integer,integer,integer,numeric,text,date,text,text,text,text)
  FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.correct_barang_masuk(integer,integer,integer,numeric,text,date,text,text,text,text)
  TO authenticated;

-- Cancel an outgoing transaction, retain its header/details, and record why.
CREATE OR REPLACE FUNCTION public.cancel_barang_keluar_audited(
  p_transaksi_id integer,
  p_alasan text
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_tx public.transaksi_keluar%ROWTYPE;
  v_details jsonb;
  v_old_data jsonb;
  v_new_data jsonb;
  v_actor_name text;
BEGIN
  IF NOT public.sipb_is_active_user() OR NOT public.sipb_is_admin() THEN
    RAISE EXCEPTION 'Hanya admin aktif yang dapat membatalkan Barang Keluar';
  END IF;
  IF length(COALESCE(trim(p_alasan),'')) < 8
     OR length(COALESCE(trim(p_alasan),'')) > 500 THEN
    RAISE EXCEPTION 'Alasan pembatalan wajib diisi minimal 8 karakter';
  END IF;

  SELECT * INTO v_tx
  FROM public.transaksi_keluar
  WHERE id = p_transaksi_id
  FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Transaksi Barang Keluar #% tidak ditemukan', p_transaksi_id;
  END IF;
  IF COALESCE(v_tx.status,'AKTIF') <> 'AKTIF' THEN
    RAISE EXCEPTION 'Transaksi #% sudah dibatalkan', p_transaksi_id;
  END IF;

  SELECT COALESCE(jsonb_agg(
    jsonb_build_object('detail',to_jsonb(d),'master_barang',to_jsonb(b))
    ORDER BY d.id
  ),'[]'::jsonb)
  INTO v_details
  FROM public.detail_barang_keluar d
  JOIN public.barang b ON b.id = d.barang_id
  WHERE d.transaksi_keluar_id = p_transaksi_id;

  v_old_data := jsonb_build_object('transaksi',to_jsonb(v_tx),'details',v_details);

  PERFORM public.cancel_barang_keluar(p_transaksi_id);

  SELECT * INTO v_tx
  FROM public.transaksi_keluar
  WHERE id = p_transaksi_id;

  v_new_data := jsonb_build_object('transaksi',to_jsonb(v_tx),'details',v_details);

  SELECT nama_lengkap INTO v_actor_name
  FROM public.user_profiles WHERE id = auth.uid();

  INSERT INTO public.sipb_transaction_audit (
    entity_type, entity_id, action, reason, actor_id, actor_name,
    old_data, new_data
  )
  VALUES (
    'BARANG_KELUAR', p_transaksi_id, 'PEMBATALAN', trim(p_alasan),
    auth.uid(), v_actor_name, v_old_data, v_new_data
  );

  RETURN jsonb_build_object('id',p_transaksi_id,'status','cancelled','audit',true);
END;
$$;

REVOKE ALL ON FUNCTION public.cancel_barang_keluar_audited(integer,text)
  FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.cancel_barang_keluar_audited(integer,text)
  TO authenticated;

-- Correct outgoing data as one atomic operation:
-- old transaction becomes DIBATALKAN, a new transaction receives the corrected
-- header/items, and both before/after snapshots are saved in one audit record.
CREATE OR REPLACE FUNCTION public.correct_barang_keluar(
  p_transaksi_id integer,
  p_tanggal date,
  p_penyerah_nama text,
  p_penyerah_jabatan text,
  p_penyerah_nip text,
  p_penerima_nama text,
  p_penerima_jabatan text,
  p_penerima_nip text,
  p_tujuan_ruangan text,
  p_jenis_dokumen text,
  p_items jsonb,
  p_alasan text
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_tx public.transaksi_keluar%ROWTYPE;
  v_details jsonb;
  v_old_data jsonb;
  v_new_data jsonb;
  v_result jsonb;
  v_new_id integer;
  v_actor_name text;
BEGIN
  IF NOT public.sipb_is_active_user() OR NOT public.sipb_is_admin() THEN
    RAISE EXCEPTION 'Hanya admin aktif yang dapat mengoreksi Barang Keluar';
  END IF;
  IF length(COALESCE(trim(p_alasan),'')) < 8
     OR length(COALESCE(trim(p_alasan),'')) > 500 THEN
    RAISE EXCEPTION 'Alasan koreksi wajib diisi minimal 8 karakter';
  END IF;

  SELECT * INTO v_tx
  FROM public.transaksi_keluar
  WHERE id = p_transaksi_id
  FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Transaksi Barang Keluar #% tidak ditemukan', p_transaksi_id;
  END IF;
  IF COALESCE(v_tx.status,'AKTIF') <> 'AKTIF' THEN
    RAISE EXCEPTION 'Hanya transaksi Barang Keluar yang masih aktif dapat dikoreksi';
  END IF;

  SELECT COALESCE(jsonb_agg(
    jsonb_build_object('detail',to_jsonb(d),'master_barang',to_jsonb(b))
    ORDER BY d.id
  ),'[]'::jsonb)
  INTO v_details
  FROM public.detail_barang_keluar d
  JOIN public.barang b ON b.id = d.barang_id
  WHERE d.transaksi_keluar_id = p_transaksi_id;
  v_old_data := jsonb_build_object('transaksi',to_jsonb(v_tx),'details',v_details);

  -- Any failure in the replacement rolls back both cancellation and stock restore.
  PERFORM public.cancel_barang_keluar(p_transaksi_id);

  v_result := public.record_barang_keluar(
    p_tanggal,
    p_penyerah_nama,
    p_penyerah_jabatan,
    p_penyerah_nip,
    p_penerima_nama,
    p_penerima_jabatan,
    p_penerima_nip,
    p_tujuan_ruangan,
    p_jenis_dokumen,
    p_items
  );
  v_new_id := (v_result->>'id')::integer;
  IF v_new_id IS NULL THEN
    RAISE EXCEPTION 'Transaksi pengganti tidak menghasilkan ID yang valid';
  END IF;

  SELECT COALESCE(jsonb_agg(
    jsonb_build_object('detail',to_jsonb(d),'master_barang',to_jsonb(b))
    ORDER BY d.id
  ),'[]'::jsonb)
  INTO v_details
  FROM public.detail_barang_keluar d
  JOIN public.barang b ON b.id = d.barang_id
  WHERE d.transaksi_keluar_id = v_new_id;

  SELECT * INTO v_tx
  FROM public.transaksi_keluar
  WHERE id = v_new_id;
  v_new_data := jsonb_build_object('transaksi',to_jsonb(v_tx),'details',v_details);

  SELECT nama_lengkap INTO v_actor_name
  FROM public.user_profiles WHERE id = auth.uid();

  INSERT INTO public.sipb_transaction_audit (
    entity_type, entity_id, new_entity_id, action, reason,
    actor_id, actor_name, old_data, new_data
  )
  VALUES (
    'BARANG_KELUAR', p_transaksi_id, v_new_id, 'KOREKSI', trim(p_alasan),
    auth.uid(), v_actor_name, v_old_data, v_new_data
  );

  RETURN jsonb_build_object(
    'status','corrected',
    'old_id',p_transaksi_id,
    'new_id',v_new_id
  );
END;
$$;

REVOKE ALL ON FUNCTION public.correct_barang_keluar(integer,date,text,text,text,text,text,text,text,text,jsonb,text)
  FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.correct_barang_keluar(integer,date,text,text,text,text,text,text,text,text,jsonb,text)
  TO authenticated;

